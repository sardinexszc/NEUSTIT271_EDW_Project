"""Time every query in docs/sample-queries.sql and write docs/query-performance.md.

Each query runs once to warm the cache, then RUNS times under EXPLAIN (ANALYZE), which reports
the server-side execution time (no network or client overhead). The report lists the median
and slowest run, the rows returned, and which scan types the plan used.

    python ingestion/benchmark_queries.py
"""

import json
import platform
import re
import statistics
from datetime import datetime

from common import ROOT, connect

QUERIES = ROOT / "docs" / "sample-queries.sql"
REPORT = ROOT / "docs" / "query-performance.md"
RUNS = 5
BUDGET_MS = 1000  # non-functional requirement NFR2: interactive queries under 1 second


def parse_queries() -> list[dict]:
    text = QUERIES.read_text(encoding="utf-8")
    parts = re.split(r"^-- @query ", text, flags=re.M)[1:]
    queries = []
    for part in parts:
        header, _, body = part.partition("\n")
        qid, title, operation = [p.strip() for p in header.split("|")]
        sql = "\n".join(line for line in body.splitlines() if not line.startswith("--")).strip().rstrip(";")
        queries.append({"id": qid, "title": title, "operation": operation, "sql": sql})
    return queries


def scan_types(plan: dict) -> set[str]:
    found = set()
    if "Scan" in plan.get("Node Type", ""):
        found.add(plan["Node Type"])
    for child in plan.get("Plans", []):
        found |= scan_types(child)
    return found


def main() -> None:
    queries = parse_queries()
    results = []
    with connect() as conn:
        version = conn.execute("show server_version").fetchone()[0]
        fact_rows = {t: conn.execute(f"select count(*) from dw.{t}").fetchone()[0] for t in
                     ["fact_damage_assessment", "fact_evacuation_snapshot",
                      "fact_resource_distribution", "fact_response_action",
                      "fact_displacement_outside", "fact_lifeline_disruption"]}
        for q in queries:
            rows = len(conn.execute(q["sql"]).fetchall())  # warm-up and row count
            times, scans = [], set()
            for _ in range(RUNS):
                plan = conn.execute("explain (analyze, format json) " + q["sql"]).fetchone()[0][0]
                times.append(plan["Planning Time"] + plan["Execution Time"])
                scans |= scan_types(plan["Plan"])
            results.append({**q, "rows": rows, "median_ms": statistics.median(times), "max_ms": max(times),
                            "scans": ", ".join(sorted(scans)) or "none"})
            print(f"{q['id']}  {statistics.median(times):8.2f} ms  {rows:>5} rows  {q['title']}")
        conn.rollback()

    slowest = max(results, key=lambda r: r["max_ms"])
    lines = [
        "# Query Performance Test Report",
        "",
        f"Generated by `ingestion/benchmark_queries.py` on {datetime.now():%Y-%m-%d %H:%M}.",
        "",
        "## Method",
        "",
        f"- Every query in [`sample-queries.sql`](sample-queries.sql) runs once to warm the cache, then "
        f"{RUNS} times under `EXPLAIN (ANALYZE)`. Times are server-side planning + execution, in milliseconds.",
        f"- Acceptance criterion (NFR2, [business case](business-case.md)): every analytical query "
        f"completes in under {BUDGET_MS} ms.",
        f"- Environment: PostgreSQL {version} on {platform.system()} {platform.release()} "
        f"({platform.machine()}), local laptop.",
        "- Data volume: " + ", ".join(f"{t} {n:,} rows" for t, n in fact_rows.items()) + ".",
        "",
        "## Results",
        "",
        f"**Table: Timing of the {len(results)} sample analytical queries.** Each query is tied to a business "
        f"question and an OLAP operation; *Median ms* is the typical time over {RUNS} runs and *Slowest ms* "
        f"the worst run, compared with the {BUDGET_MS} ms budget.",
        "",
        "| Query | Business question | OLAP operation | Rows | Median ms | Slowest ms | Within budget |",
        "|---|---|---|---:|---:|---:|---|",
    ]
    for r in results:
        ok = "Yes" if r["max_ms"] < BUDGET_MS else "**No**"
        lines.append(f"| {r['id']} | {r['title']} | {r['operation']} | {r['rows']:,} | "
                     f"{r['median_ms']:.2f} | {r['max_ms']:.2f} | {ok} |")
    passed = sum(r["max_ms"] < BUDGET_MS for r in results)
    lines += [
        "",
        "## Findings",
        "",
        f"- **{passed} of {len(results)} queries** meet the {BUDGET_MS} ms budget on every run; the slowest "
        f"single run was {slowest['id']} at {slowest['max_ms']:.1f} ms.",
    ]
    by_id = {r["id"]: r for r in results}
    if "Q01" in by_id and "Q13" in by_id:
        lines.append(
            f"- **Marts pay off:** the event headline read from `mart.mart_event_summary` (Q13, "
            f"{by_id['Q13']['median_ms']:.2f} ms) is about {by_id['Q01']['median_ms'] / by_id['Q13']['median_ms']:.0f}× "
            f"faster than aggregating the same figures from the fact table (Q01, {by_id['Q01']['median_ms']:.2f} ms). "
            "This is why the dashboards read marts, not facts.")
    lines += [
        "- **Sequential scans are the right plan at this size.** With tens of thousands of rows per fact, "
        "PostgreSQL reads each table in a few milliseconds and chooses sequential scans over indexes. At national "
        "scale (millions of rows) the next step is B-tree indexes on the fact foreign keys most used in filters "
        "(`event_key`, `location_key`, date keys) and partitioning facts by event year; this benchmark is the "
        "baseline to measure that against.",
        "- Plans per query (scan types used):",
        "",
    ]
    lines += [f"  - {r['id']}: {r['scans']}" for r in results]
    lines.append("")
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    (ROOT / "docs" / "query-performance.json").write_text(
        json.dumps([{k: v for k, v in r.items() if k != "sql"} for r in results], indent=2), encoding="utf-8")
    print(f"\nwrote {REPORT}")


if __name__ == "__main__":
    main()
